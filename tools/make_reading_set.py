def viewer_url(r):
    return ("https://newslibrary.naver.com/viewer/index.naver?"
            f"articleId={r['articleId']}&editNo={r['editNo']}&printCount=1&publishDate={r['publishDate']}"
            f"&officeId={r['officeId']}&pageNo={r['pageNo']}&printNo={r['printNo']}&publishType={r['publishType']}")


def one_line(s):
    return re.sub(r"\s+", " ", s).strip()


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    recs = [json.loads(l) for l in open(sys.argv[1], encoding="utf-8")]
    out_dir = Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)
    index = []
    for no, stage, idxs, short, author, cls, how, points in ITEMS:
        parts = [recs[i - 1] for i in idxs]
        first, last = parts[0], parts[-1]
        paper = PAPER.get(first["officeId"], first["officeName"])
        genre = GENRE.get(first["articleGenre"], first["articleGenre"])
        date = first["publishDate"] if len(parts) == 1 else f"{first['publishDate']} ~ {last['publishDate']}"
        chars = sum(len(p["read"]) for p in parts)
        fname = f"{no:02d}_{first['publishDate']}_{paper[:2]}_{short}.md"
        title_read = one_line(first["titleRead"])
        title_han = one_line(first["title"])
        if len(parts) > 1:  # 연재물은 회차 표시를 뗀다
            title_read = re.sub(r"\s*\([^()]*\)\s*$", "", title_read)
            title_han = re.sub(r"\s*\([^()]*(\([^()]*\))?[^()]*\)\s*$", "", title_han)
        lines = [
            f"# {no:02d}. 「{title_read}」",
            "",
            "| 항목 | 내용 |",
            "|---|---|",
            f"| 원제 | {title_han} |",
            f"| 신문 | 『{paper}』 |",
            f"| 날짜·면 | {date}, {first['pageNo']}면" + (f" ({len(parts)}회분)" if len(parts) > 1 else "") + " |",
            f"| 장르 | {genre} |",
            f"| 필자·성격 | {author} |",
            f"| 분류 | {cls} |",
            f"| 분량 | 약 {chars:,}자 |",
            f"| 읽는 법 | {how} |",
            "",
            "## 읽기 포인트",
            "",
            *[f"- {p}" for p in points],
            "",
            "> 아래 본문은 네이버 뉴스라이브러리의 자동 판독 텍스트를 한글 독음으로 바꾼 것이다. □는 판독 불가 글자다. 띄어쓰기가 원문과 다르고 오자가 있으니, **인용할 문장은 반드시 원문 지면 이미지로 확인**한다. 한자 병기본은 맨 아래에 있다.",
            "",
            "## 본문 (한글 독음)",
            "",
        ]
        for p in parts:
            if len(parts) > 1:
                lines += [f"### {one_line(p['titleRead'])} — {p['publishDate']}", ""]
            lines += [f"[원문 지면 보기]({viewer_url(p)})", "", p["read"], ""]
        lines += ["---", "", "<details>", "<summary>한자 병기본 (인용할 때 원문 대조용)</summary>", ""]
        for p in parts:
            if len(parts) > 1:
                lines += [f"### {one_line(p['titleMixed'])} — {p['publishDate']}", ""]
            lines += [p["mixed"], ""]
        lines += ["</details>", ""]
        (out_dir / fname).write_text("\n".join(lines), encoding="utf-8")
        index.append((no, stage, date, paper, genre, title_read, title_han, fname, chars, how))
    for row in index:
        print(*row, sep=" | ")


if __name__ == "__main__":
    main()
